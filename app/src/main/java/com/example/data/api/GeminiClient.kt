    private val mediaType = "application/json; charset=utf-8".toMediaType()

    suspend fun generateContent(systemInstructions: String, userPrompt: String): String = withContext(Dispatchers.IO) {
        val apiKey = try {
            BuildConfig.GEMINI_API_KEY
        } catch (e: Exception) {
            ""
        }

        if (apiKey.isEmpty() || apiKey == "MY_GEMINI_API_KEY") {
            Log.w(TAG, "Gemini API key is not set. Generating quality simulated response.")
            return@withContext getSimulatedResponse(systemInstructions, userPrompt)
        }

        try {
            val url = "$BASE_URL?key=$apiKey"
            
            val jsonBody = JSONObject().apply {
                val contentsArr = JSONArray().apply {
                    put(JSONObject().apply {
                        put("parts", JSONArray().apply {
                            put(JSONObject().apply {
                                put("text", userPrompt)
                            })
                        })
                    })
                }
                put("contents", contentsArr)

                if (systemInstructions.isNotEmpty()) {
                    put("systemInstruction", JSONObject().apply {
                        put("parts", JSONArray().apply {
                            put(JSONObject().apply {
                                put("text", systemInstructions)
                            })
                        })
                    })
                }

                put("generationConfig", JSONObject().apply {
                    put("temperature", 0.7)
                })
            }

            val request = Request.Builder()
                .url(url)
                .post(jsonBody.toString().toRequestBody(mediaType))
                .header("Content-Type", "application/json")
                .build()

            client.newCall(request).execute().use { response ->
                if (!response.isSuccessful) {
                    val errorBody = response.body?.string() ?: ""
                    Log.e(TAG, "API Call Failed: code=${response.code}, body=$errorBody")
                    return@withContext "Error: Gemini API error (Code ${response.code}). Falling back to simulation:\n\n${getSimulatedResponse(systemInstructions, userPrompt)}"
                }

                val responseBodyStr = response.body?.string() ?: return@withContext "No response from Gemini API"
                val jsonResponse = JSONObject(responseBodyStr)
                val candidates = jsonResponse.optJSONArray("candidates")
                if (candidates != null && candidates.length() > 0) {
                    val firstCandidate = candidates.getJSONObject(0)
                    val content = firstCandidate.getJSONObject("content")
                    val parts = content.getJSONArray("parts")
                    if (parts.length() > 0) {
                        return@withContext parts.getJSONObject(0).optString("text", "Empty response text")
                    }
                }
                return@withContext "No text generated by Gemini"
            }
        } catch (e: Exception) {
            Log.e(TAG, "Gemini API exception", e)
            return@withContext "An error occurred: ${e.localizedMessage}. Fallback simulation:\n\n${getSimulatedResponse(systemInstructions, userPrompt)}"
        }
    }

